export default function FAQPage() {
  const [query, setQuery] = useState('')

  const filtered = query.trim()
    ? faqCategories.map(cat => ({
        ...cat,
        items: cat.items.filter(
          item =>
            item.q.toLowerCase().includes(query.toLowerCase()) ||
            item.a.toLowerCase().includes(query.toLowerCase())
        ),
      })).filter(cat => cat.items.length > 0)
    : faqCategories

  const loading = usePageSkeleton(450)

  return (
    <Skeleton
      name="faq-page"
      loading={loading}
      animate="shimmer"
      color="rgba(163, 177, 198, 0.40)"
      darkColor="rgba(255, 255, 255, 0.08)"
      transition={300}
      fallback={<FAQSkeletonFallback />}
    >
      <SEO
        title="Frequently Asked Questions — Payments, Formats & Privacy | PrintBooth"
        description="Got questions about PrintBooth? Learn about UPI payments, zero-cloud file security, supported document formats, refund policies, and kiosk hardware."
        canonicalUrl="https://printbooth.in/faq"
        breadcrumbs={[
          { name: 'Home', url: '/' },
          { name: 'FAQ', url: '/faq' },
        ]}
        schema={{
          '@type': 'FAQPage',
          mainEntity: faqCategories.flatMap(cat =>
            cat.items.map(item => ({
              '@type': 'Question',
              name: item.q,
              acceptedAnswer: {
                '@type': 'Answer',
                text: item.a,
              },
            }))
          ),
        }}
      />
      <div className="sub-page">
      {/* Hero */}
      <div className="sub-hero">
        <div className="container">
          <div className="sub-hero__inner">
            <span className="sub-hero__eyebrow">
              <span className="sub-hero__eyebrow-dot" />
              FAQ
            </span>
            <h1 className="sub-hero__title">
              Frequently Asked{' '}
              <span className="sub-hero__title-accent">Questions</span>
            </h1>
            <p className="sub-hero__sub">
              Everything you need to know about using PrintBooth — from uploading files to getting your prints.
            </p>
          </div>
        </div>
      </div>

      <div className="container sub-content">
        {/* Search */}
        <div style={{ position: 'relative', maxWidth: 480 }}>
          <MagnifyingGlass
            size={16}
            style={{
              position: 'absolute',
              left: 16,
              top: '50%',
              transform: 'translateY(-50%)',
              color: 'var(--neo-text-4)',
              pointerEvents: 'none',
            }}
          />
          <input
            className="neo-input"
            style={{ paddingLeft: 42 }}
            type="search"
            placeholder="Search questions…"
            value={query}
            onChange={e => setQuery(e.target.value)}
            id="faq-search"
          />
        </div>

        {/* FAQ Categories */}
        {filtered.length === 0 ? (
          <div className="neo-card-inset" style={{ textAlign: 'center', padding: '48px 24px' }}>
            <p style={{ color: 'var(--neo-text-4)', fontSize: 15 }}>
              No questions match "<strong>{query}</strong>". Try a different term or{' '}
              <a href="/support" style={{ color: 'var(--neo-accent-lt)' }}>contact support</a>.
            </p>
          </div>
        ) : (
          filtered.map(cat => (
            <div key={cat.category}>
              <h2 className="sub-heading">{cat.category}</h2>
              <div className="neo-faq-list">
                {cat.items.map((faq, i) => (
                  <details key={i} className="neo-faq-item">
                    <summary>
                      <span>{faq.q}</span>
                      <span className="neo-faq-chevron" aria-hidden="true">+</span>
                    </summary>
                    <div className="neo-faq-body">{faq.a}</div>
                  </details>
                ))}
              </div>
            </div>
          ))
        )}

        {/* CTA */}
        <div className="neo-card" style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', gap: 20, flexWrap: 'wrap' }}>
          <div>
            <p style={{ fontWeight: 700, fontSize: 16, color: 'var(--neo-text-1)', marginBottom: 4 }}>
              Still have questions?
            </p>
            <p style={{ fontSize: 14, color: 'var(--neo-text-3)' }}>
              Our support team is ready to help within one business day.
            </p>
          </div>
          <a href="/support" className="neo-btn neo-btn-primary">
            Contact Support
          </a>
        </div>
      </div>
    </div>
    </Skeleton>
  )
}
